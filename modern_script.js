document.addEventListener('DOMContentLoaded', () => {
    showDialogue();
});

function showDialogue() {
  if(getStorage("is-ugly", false)){
    setStorage("is-ugly", false);
    if(window.confirm("There. Better now?")) {
      confetti();
    }else{
      const text = window.prompt("Feel free to leave your worst insults here. I will read them and cry.");
      if(text) {
        addDBEntry("feedback: " + text);
      }
      clickLink("index.html");
    }
  }
}


// Classic "ta-dah!" confetti: two cannons fire from the bottom corners,
// pieces flutter down, then the overlay canvas removes itself.
// Shamelessly generated by Claude.
function confetti(){
  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;

  const canvas = document.createElement("canvas");
  canvas.style.cssText = "position:fixed;inset:0;width:100%;height:100%;pointer-events:none;z-index:9999";
  document.body.appendChild(canvas);
  const ctx = canvas.getContext("2d");
  const dpr = window.devicePixelRatio || 1;
  const W = window.innerWidth, H = window.innerHeight;
  canvas.width = W * dpr;
  canvas.height = H * dpr;
  ctx.scale(dpr, dpr);

  const colors = ["#ff595e", "#ffca3a", "#8ac926", "#1982c4", "#6a4c93", "#ff924c"];
  const pieces = [];
  for (let i = 0; i < 160; i++) {
    const fromLeft = i % 2 === 0;
    // Aim up and toward the middle of the screen
    const angle = (fromLeft ? -60 : -120) * Math.PI / 180 + (Math.random() - 0.5) * 0.7;
    const speed = 30 + Math.random() * 30;
    pieces.push({
      x: fromLeft ? 0 : W,
      y: H,
      vx: Math.cos(angle) * speed,
      vy: Math.sin(angle) * speed * (H / 700),
      w: 6 + Math.random() * 6,
      h: 8 + Math.random() * 8,
      color: colors[Math.floor(Math.random() * colors.length)],
      rot: Math.random() * Math.PI * 2,
      vrot: (Math.random() - 0.5) * 0.3,
      tilt: Math.random() * Math.PI * 2,
    });
  }

  const start = performance.now();
  const duration = 2000;
  function frame(now){
    const elapsed = now - start;
    ctx.clearRect(0, 0, W, H);
    // Fade out over the last second
    ctx.globalAlpha = Math.min(1, (duration - elapsed) / 1000);
    for (const p of pieces) {
      p.vy += 1.45;          // gravity
      p.vx *= 0.99;         // air drag
      p.vy *= 0.99;
      p.x += p.vx;
      p.y += p.vy;
      p.rot += p.vrot;
      p.tilt += 0.1;
      ctx.save();
      ctx.translate(p.x, p.y);
      ctx.rotate(p.rot);
      ctx.scale(1, Math.cos(p.tilt)); // flip like paper
      ctx.fillStyle = p.color;
      ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
      ctx.restore();
    }
    if (elapsed < duration) {
      requestAnimationFrame(frame);
    } else {
      canvas.remove();
    }
  }
  requestAnimationFrame(frame);
}

